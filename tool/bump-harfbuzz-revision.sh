set -euo pipefail

# Script to update the bundled HarfBuzz revision and regenerate sources.cmake.
# Usage: ./tool/bump-harfbuzz-revision.sh [revision] [--dry-run]

DRY_RUN=false
TARGET_REVISION=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --dry-run)
      DRY_RUN=true
      shift
      ;;
    -*)
      echo "Unknown option: $1" >&2
      exit 1
      ;;
    *)
      TARGET_REVISION="$1"
      shift
      ;;
  esac
done

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd )"
ROOT="$DIR/.."
REVISION_FILE="$DIR/REVISION"
HARFBUZZ_REPOSITORY="https://github.com/harfbuzz/harfbuzz.git"

if [[ -z "$TARGET_REVISION" ]]; then
  TARGET_REVISION="$(git -c url."https://github.com/".insteadOf="https://github.com/" ls-remote "$HARFBUZZ_REPOSITORY" HEAD | awk '{print $1}')"
fi

SHORT_REVISION="${TARGET_REVISION:0:9}"
if [[ -n "${GITHUB_OUTPUT:-}" ]]; then
  echo "revision=$TARGET_REVISION" >> "$GITHUB_OUTPUT"
  echo "short_revision=$SHORT_REVISION" >> "$GITHUB_OUTPUT"
fi

if [[ "$DRY_RUN" == "true" ]]; then
  echo "[info] Target revision: $TARGET_REVISION"
  exit 0
fi

TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

echo "[info] Cloning HarfBuzz at $TARGET_REVISION..."
git init "$TMP_DIR/harfbuzz" >/dev/null 2>&1
git -C "$TMP_DIR/harfbuzz" remote add origin "$HARFBUZZ_REPOSITORY"
git -c url."https://github.com/".insteadOf="https://github.com/" -C "$TMP_DIR/harfbuzz" fetch --depth 1 origin "$TARGET_REVISION" >/dev/null 2>&1
git -C "$TMP_DIR/harfbuzz" checkout --detach FETCH_HEAD >/dev/null 2>&1

DEST="$ROOT/third_party/harfbuzz"
rm -rf "$DEST"
mkdir -p "$DEST/src"

cp "$TMP_DIR/harfbuzz/COPYING" "$DEST/COPYING"

python3 - "$TMP_DIR/harfbuzz/src" "$DEST" <<'PY'
import os
import re
import shutil
import sys

src_dir = os.path.abspath(sys.argv[1])
dest_root = os.path.abspath(sys.argv[2])
dest_src = os.path.join(dest_root, "src")

with open(os.path.join(src_dir, "harfbuzz-subset.cc"), encoding="utf-8") as f:
    cc_files = re.findall(r'#include\s+"([^"]+)"', f.read())

cc_set = set(cc_files)
cc_set.add("harfbuzz-subset.cc")

for root, _, files in os.walk(src_dir):
    for fn in files:
        full = os.path.join(root, fn)
        rel = os.path.relpath(full, src_dir).replace("\\", "/")
        if fn.endswith((".h", ".hh")) or rel in cc_set:
            out_path = os.path.join(dest_src, rel)
            os.makedirs(os.path.dirname(out_path), exist_ok=True)
            shutil.copy2(full, out_path)

sources_cmake = os.path.join(dest_root, "sources.cmake")
with open(sources_cmake, "w", encoding="utf-8") as f:
    f.write("# GENERATED BY tool/bump-harfbuzz-revision.sh. DO NOT EDIT.\n\n")
    f.write("set(\n  harfbuzz_subset_sources\n")
    for cc in sorted(cc_files):
        f.write(f"  ${{HARFBUZZ_ROOT}}src/{cc}\n")
    f.write(")\n")
PY

echo "$TARGET_REVISION" > "$REVISION_FILE"
echo "[ok] Updated third_party/harfbuzz to $TARGET_REVISION"
